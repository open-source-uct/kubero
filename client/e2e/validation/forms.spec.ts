import { test, expect, field, pipeline } from './fixtures'

test('apps block invalid ports, validate on blur, and send exactly one valid request', async ({ page, writes }) => {
  await page.goto('/pipeline/course/production/apps/new')
  const name = field(page, 'name')
  await name.fill('course-app')
  const port = field(page, 'port')
  await port.fill('invalid')
  await expect(port).not.toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('.v-input').filter({ has: port })).toContainText('whole number')
  await port.press('Tab')
  await expect(port).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('button[type="submit"]')).toBeDisabled()
  await port.press('Enter')
  expect(writes).toHaveLength(0)
  await port.fill('65535')
  await expect(port).not.toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('button[type="submit"]')).toBeEnabled()
  await port.press('Enter')
  await expect.poll(() => writes.filter(request => request.path.startsWith('/api/apps/')).length).toBe(1)
  expect(writes[0].body.image).toMatchObject({ containerPort: '65535' })
})


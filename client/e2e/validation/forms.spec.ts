test('account creation blocks invalid email and password and resets feedback on reopen', async ({ page, writes }) => {
  await page.goto('/accounts/users')
  await expect(page.getByText('student', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Create/i }).first().click()
  const dialog = page.getByRole('dialog')
  await field(page, 'username').fill('María José')
  await field(page, 'email').fill('invalid')
  await field(page, 'password').fill('short')
  await expect(dialog.locator('button[type="submit"]')).toBeDisabled()
  await field(page, 'email').press('Tab')
  await expect(field(page, 'email')).toHaveAttribute('aria-invalid', 'true')
  await field(page, 'email').fill('maria@example.test')
  await field(page, 'password').fill('abcdefgh')
  await dialog.locator('button[type="submit"]').click()
  await expect.poll(() => writes.length).toBe(1)
  expect(writes[0].body.username).toBe('María José')
  await page.getByRole('button', { name: /Create/i }).first().click()
  await expect(field(page, 'email')).not.toHaveAttribute('aria-invalid', 'true')
  await expect(dialog.locator('button[type="submit"]')).toBeDisabled()
})

